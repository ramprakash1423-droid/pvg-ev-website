CREATE OR REPLACE FUNCTION pvg_app.notify_change() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE d jsonb; old_d jsonb; booking text; owners jsonb := '[]'; owner_id text;
BEGIN
 d := CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 old_d := CASE WHEN TG_OP='UPDATE' THEN to_jsonb(OLD) ELSE '{}'::jsonb END;
 IF TG_TABLE_NAME='bookings' THEN
  booking := d->>'id'; owners := jsonb_build_array(d->>'customer_id',d->>'technician_id',old_d->>'technician_id');
 ELSIF TG_TABLE_NAME IN ('booking_tracking','readings','invoices','audit') THEN
  booking:=d->>'booking_id';
  SELECT jsonb_build_array(customer_id,technician_id) INTO owners FROM pvg_app.bookings WHERE id=booking;
 ELSIF TG_TABLE_NAME IN ('evs','places','customer_preferences','users') THEN
  owner_id:=coalesce(d->>'customer_id',d->>'user_id',d->>'id'); owners:=jsonb_build_array(owner_id);
 END IF;
 PERFORM pg_notify('pvg_app_changes',jsonb_build_object('kind',TG_TABLE_NAME,'booking_id',booking,'users',coalesce(owners,'[]'::jsonb))::text);
 RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION pvg_app.notify_change() FROM PUBLIC,anon,authenticated;
